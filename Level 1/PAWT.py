def draw_square(x, y, color):
    t.penup()
    t.goto(x, y)
    t.pendown()
    t.color(color)
    t.begin_fill()
    for _ in range(4):
        t.forward(pixel_size)
        t.right(90)
    t.end_fill()

def draw_bottom_border(start_x, start_y):
    for i in range(40):
        if i % 3 == 0:
            clr = "dimgray"
        elif i % 3 == 1:
            clr = "darkgoldenrod"
        else:
            clr = "gray"
        draw_square(start_x + (i * pixel_size), start_y, clr)

